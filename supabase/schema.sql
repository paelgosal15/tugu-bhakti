-- Jalankan sekali di Supabase > SQL Editor. Aman dijalankan ulang.

create table if not exists public.site_settings (key text primary key, value text not null default '');
create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  slug text,
  title text not null,
  intro text not null default '',
  layout text not null default 'cards' check (layout in ('text','cards','timeline','steps','numbered')),
  visible boolean not null default true,
  sort_order int not null default 0
);
create table if not exists public.items (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id) on delete cascade,
  title text not null default '',
  subtitle text not null default '',
  body text not null default '',
  image_url text not null default '',
  sort_order int not null default 0
);
create table if not exists public.admins (user_id uuid primary key references auth.users(id) on delete cascade);
create table if not exists public.chat_logs (
  id bigint generated by default as identity primary key,
  question text not null, answer text, created_at timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql security definer stable set search_path = public
as $$ select exists (select 1 from public.admins where user_id = auth.uid()); $$;

alter table public.site_settings enable row level security;
alter table public.sections enable row level security;
alter table public.items enable row level security;
alter table public.admins enable row level security;
alter table public.chat_logs enable row level security;

do $$ declare t text; begin
  foreach t in array array['site_settings','sections','items'] loop
    execute format('drop policy if exists "baca %1$s" on public.%1$s', t);
    execute format('create policy "baca %1$s" on public.%1$s for select using (true)', t);
    execute format('drop policy if exists "admin %1$s" on public.%1$s', t);
    execute format('create policy "admin %1$s" on public.%1$s for all using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;
drop policy if exists "admin baca diri" on public.admins;
create policy "admin baca diri" on public.admins for select using (user_id = auth.uid());
drop policy if exists "admin baca log" on public.chat_logs;
create policy "admin baca log" on public.chat_logs for select using (public.is_admin());
drop policy if exists "admin hapus log" on public.chat_logs;
create policy "admin hapus log" on public.chat_logs for delete using (public.is_admin());

